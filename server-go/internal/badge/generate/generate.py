"""Converts the character width tables of anafanafo (MIT, Metabolize LLC), which badge-maker
measures text with, into the compact files in ../data, and the CSS colour names of color-name
(MIT, DY), which badge-maker accepts as colours, into ../css_colors.go.

Usage: python3 -I generate.py <node_modules dir that has anafanafo>

Each file is gzip of unsigned varints, three per range of code points: the gap from the end of
the previous range, the range's length minus one, and the width in hundredths of a pixel.
"""

import gzip
import json
import os
import sys

FONTS = ["verdana-10px-normal", "verdana-10px-bold", "verdana-11px-normal", "helvetica-11px-bold"]


def uvarint(value):
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        if value:
            out.append(byte | 0x80)
        else:
            out.append(byte)
            return bytes(out)


def main():
    modules = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    for font in FONTS:
        with open(os.path.join(modules, "anafanafo", "data", font + ".json")) as f:
            ranges = json.load(f)
        out = bytearray()
        previous = -1
        for lower, upper, width in ranges:
            hundredths = round(width * 100)
            assert abs(hundredths / 100 - width) < 1e-9, (font, lower, width)
            assert lower > previous and upper >= lower
            out += uvarint(lower - previous - 1) + uvarint(upper - lower) + uvarint(hundredths)
            previous = upper
        path = os.path.join(here, "..", "data", font + ".bin.gz")
        with gzip.GzipFile(path, "wb", mtime=0) as f:
            f.write(bytes(out))
        print(font, len(ranges), "ranges,", os.path.getsize(path), "bytes")

    import subprocess

    names = json.loads(
        subprocess.check_output(
            ["node", "-e", "console.log(JSON.stringify(require(process.argv[1])))", os.path.join(modules, "color-name")]
        )
    )
    lines = ["// Code generated by generate/generate.py from color-name (MIT). DO NOT EDIT.", "", "package badge", ""]
    lines.append("// cssColors are the CSS colour names, which badge-maker accepts besides its own.")
    lines.append("var cssColors = map[string][3]uint8{")
    for name in sorted(names):
        r, g, b = names[name]
        lines.append(f'\t"{name}": {{{r}, {g}, {b}}},')
    lines.append("}")
    go_path = os.path.join(here, "..", "css_colors.go")
    with open(go_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    subprocess.check_call(["gofmt", "-w", go_path])
    print(len(names), "CSS colours")


if __name__ == "__main__":
    main()
